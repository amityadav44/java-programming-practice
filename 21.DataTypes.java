

 class DataType {
    public static void main(String[] args) {
        System.out.println("📌 Primitive Data Types in Java with Output\n");

        int x = 5;
        float y = 5f;
        char c = 'A';
        boolean b = true;
        byte w = 4;
        short e = 43;
        long d = 4L;
        double m = 4;

        System.out.println("🔹 Integer value: " + x);
        System.out.println("🔹 Float value: " + y);
        System.out.println("🔹 Char value: " + c);
        System.out.println("🔹 Boolean value: " + b);
        System.out.println("🔹 Byte value: " + w);
        System.out.println("🔹 Short value: " + e);
        System.out.println("🔹 Long value: " + d);
        System.out.println("🔹 Double value: " + m);
    }
}
