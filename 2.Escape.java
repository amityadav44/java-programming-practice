 class Escape {
    public static void main(String[] args) {
        System.out.println("Hello  ! I am Amit  ");
        System.out.println("Hello\tI am Amit "); // space ko badhta hai
        System.out.println("Hello  \bBaby ");// ek space ko kam krta hai
        System.out.print("Hello How are you\n");// curcer niichy aa jata hai
        System.out.println("Hello \" Yadav\" ji");
        System.out.println("Hello Baby \'How are you \'What are you  doing  ");
        System.out.println("Hii Amit \\How are \\you ");
    }
}
